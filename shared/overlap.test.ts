import { describe, it } from 'vitest'

// 対象：shared/overlap.ts の findOverlaps
// TASK.md T06 完了条件「重なる／重ならない／端が接する／進行中の記録との重なり／自分自身は除外」
// 判定の根拠：SPEC 3章「時間の重なり」（終了時刻と次の開始時刻がちょうど一致する場合は重なりとみなさない）、
//             SPEC 7.2 の排他制約の範囲 tstzrange(started_at, coalesce(ended_at, 'infinity'), '[)')
// 日時はすべて JST（+09:00）の ISO 8601 文字列で書く（SPEC 3章「タイムゾーン」、SPEC 8.1）
describe('findOverlaps', () => {
  // SPEC 3章「時間の重なり」：重ならない場合は何も返さない
  describe('重ならない', () => {
    it.todo('既存の記録が空配列のとき、空配列を返す（空データ）')
    it.todo('対象の開始より前に終わる記録は返さない（既存 9:00〜10:00、対象 11:00〜12:00）')
    it.todo('対象の終了より後に始まる記録は返さない（既存 13:00〜14:00、対象 11:00〜12:00）')
  })

  // SPEC 3章「終了時刻と次の開始時刻がちょうど一致する場合は重なりとみなさない」、SPEC 7.2 の '[)'
  describe('端が接する', () => {
    it.todo(
      '既存の終了と対象の開始が一致する記録は返さない（既存 10:00〜11:00、対象 11:00〜12:00）',
    )
    it.todo(
      '対象の終了と既存の開始が一致する記録は返さない（既存 12:00〜13:00、対象 11:00〜12:00）',
    )
    it.todo(
      '前後の記録の両方と端が接するとき、空配列を返す（10:00〜11:00 と 12:00〜13:00、対象 11:00〜12:00）',
    )
  })

  // SPEC 3章「時間の重なり」：一部でも時間が重なる記録を返す
  describe('重なる', () => {
    it.todo('対象の開始をまたぐ記録を返す（既存 10:00〜11:30、対象 11:00〜12:00）')
    it.todo('対象の終了をまたぐ記録を返す（既存 11:30〜13:00、対象 11:00〜12:00）')
    it.todo('対象を含む記録を返す（既存 10:00〜13:00、対象 11:00〜12:00）')
    it.todo('対象に含まれる記録を返す（既存 11:15〜11:45、対象 11:00〜12:00）')
    it.todo('対象とまったく同じ範囲の記録を返す（既存 11:00〜12:00、対象 11:00〜12:00）')
    it.todo('重なりが1秒だけの記録も返す（既存 10:00〜11:00:01、対象 11:00〜12:00）')
  })

  // SPEC 3章「日付をまたぐ記録」は1件のまま保存するため、0:00 で区切らずに判定する
  describe('0:00 をまたぐ記録', () => {
    it.todo(
      '0:00 をまたぐ既存の記録と、翌日の朝の対象が重なるとき、その記録を返す（既存 23:00〜翌 7:00、対象 翌 6:30〜8:00）',
    )
    it.todo(
      '0:00 をまたぐ対象と、前日の夜の既存の記録が重なるとき、その記録を返す（既存 22:00〜23:30、対象 23:00〜翌 1:00）',
    )
    it.todo('0:00 ちょうどで端が接する記録は返さない（既存 22:00〜翌 0:00、対象 翌 0:00〜1:00）')
  })

  // SPEC 7.1「ended_at が null = 進行中」、SPEC 7.2 の coalesce(ended_at, 'infinity')
  describe('進行中の記録', () => {
    describe('既存の記録が進行中', () => {
      it.todo(
        '進行中の記録の開始より後の対象と重なるとき、その記録を返す（既存 9:00〜進行中、対象 10:00〜11:00）',
      )
      it.todo(
        '進行中の記録の開始より前に終わる対象とは重ならない（既存 9:00〜進行中、対象 7:00〜8:00）',
      )
      it.todo(
        '対象の終了と進行中の記録の開始が一致するときは返さない（既存 9:00〜進行中、対象 8:00〜9:00）',
      )
      it.todo(
        '進行中の記録の終了は現在時刻ではなく無限大とみなす（現在時刻を 10:00 に固定し、既存 9:00〜進行中、対象 11:00〜12:00 で返す）',
      )
    })
    describe('判定対象が進行中', () => {
      it.todo('対象の開始より後に始まる記録を返す（既存 10:00〜11:00、対象 9:00〜進行中）')
      it.todo('対象の開始をまたぐ記録を返す（既存 8:00〜9:30、対象 9:00〜進行中）')
      it.todo(
        '既存の終了と対象の開始が一致する記録は返さない（既存 8:00〜9:00、対象 9:00〜進行中）',
      )
      it.todo('対象の開始より前に終わる記録は返さない（既存 7:00〜8:00、対象 9:00〜進行中）')
    })
    it.todo(
      '既存の記録と判定対象の両方が進行中のとき、その記録を返す（既存 9:00〜進行中、対象 10:00〜進行中）',
    )
  })

  // 修正（SPEC 5.7、SPEC 8.2 PATCH /api/entries/:id）では、修正前の自分自身と重なってもエラーにしない
  describe('自分自身の除外', () => {
    it.todo('対象の id と同じ id の記録は、時間が重なっていても返さない')
    it.todo(
      '修正で時間をずらしたとき、自分自身を除いた重なる記録だけを返す（自分 10:00〜11:00 を 10:30〜11:30 に変更し、11:00〜12:00 の記録と重なる）',
    )
    it.todo('対象の id を省略したとき（追加）は、重なるすべての記録を返す')
    it.todo(
      '進行中の自分自身の開始時刻を変更するとき、自分自身は返さない（自分 9:00〜進行中 を 8:30〜進行中 に変更）',
    )
  })

  // SPEC 3章「重なっている記録を表示する」、SPEC 8.1 の conflicts（TimeEntry[]）
  describe('複数の記録', () => {
    it.todo('重なる記録をすべて返し、重ならない記録・端が接する記録は返さない')
    it.todo('戻り値は渡した記録の順序を保つ')
    it.todo('戻り値の要素は渡した記録そのもので、category_id などの他の項目も保たれる')
    it.todo('渡した記録の配列を変更しない')
  })

  // SPEC 8.1「日時は ISO 8601 形式の文字列」：表記ではなく瞬間として比較する
  describe('時刻の表記の違い', () => {
    it.todo(
      'オフセットが違っても同じ瞬間なら端が接するとみなし、返さない（既存の終了 11:00+09:00、対象の開始 02:00Z）',
    )
    it.todo(
      'オフセットが違っても瞬間として重なっていれば返す（既存 01:30Z〜02:30Z、対象 11:00+09:00〜12:00+09:00）',
    )
    it.todo(
      'ミリ秒の有無が違っても同じ瞬間なら端が接するとみなし、返さない（既存の終了 11:00:00.000+09:00、対象の開始 11:00:00+09:00）',
    )
    it.todo(
      '文字列の辞書順では前後が逆になる表記でも、瞬間で比較する（既存 10:30+09:00〜02:30Z、対象 11:00+09:00〜12:00+09:00 で返す）',
    )
    // SPEC 8.1・7.1：started_at / ended_at は timestamptz で、Supabase（PostgREST）は
    // オフセット +00:00・小数部6桁の形式で返すため、その表記の既存記録とも瞬間で比較できることを確かめる
    it.todo(
      'Supabase が返す timestamptz の形式（+00:00・小数部6桁）の既存記録でも、同じ瞬間なら端が接するとみなし、返さない（既存の終了 2026-10-24T02:00:00.000000+00:00、対象の開始 2026-10-24T11:00:00+09:00）',
    )
  })
})
